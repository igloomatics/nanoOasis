"""Interactive Breakout play using a frozen VAE and DiT world model.

Arrow keys/A,D choose the paddle action. The first context is generated by the
real Breakout game; after that every displayed frame is predicted by the DiT.
This is a model demo, not a rules-enforced game.
"""
import argparse
import numpy as np
import torch

from game import W, H, LEFT, NONE, RIGHT, Game
from data_gen import SeekBot
from infer_breakout import decode_latent, make_schedule, sample_next_frame
from model import DiT
from vae import VAE
from diffusion import EDMDiffusion
from omegaconf import OmegaConf


def load_models(args, device):
    cfg = OmegaConf.load(f"configs/{args.config}.yaml")
    vae = VAE(cfg.vae).to(device).eval()
    vae.load_state_dict(torch.load(args.vae, map_location=device, weights_only=False)["model"])
    model = DiT(cfg.dit).to(device).eval()
    ck = torch.load(args.ckpt, map_location=device, weights_only=False)
    state = ck.get("ema", ck["model"]) if not getattr(args, "raw", False) else ck["model"]
    # DDP training checkpoints may retain the wrapper's `module.` prefix.
    if state and next(iter(state)).startswith("module."):
        state = {k[7:]: v for k, v in state.items()}
    model.load_state_dict(state)
    diff = EDMDiffusion(model, cfg.diffusion).to(device).eval()
    return cfg, vae, diff


@torch.no_grad()
def initial_context(vae, cfg, seed, device):
    g = Game(seed)
    bot = SeekBot(np.random.default_rng(seed))
    frames, actions = [], []
    for _ in range(int(cfg.dit.context_frames)):
        a = bot.act(g)
        frames.append(g.step(a)[0])
        actions.append(a)
    x = torch.from_numpy(np.stack(frames)).to(device)
    mu, _ = vae.encode(x)
    z = mu.reshape(1, len(frames), vae.Hp, vae.Wp, vae.latent_channels)
    z = z.permute(0, 1, 4, 2, 3).contiguous()
    return z, actions


def poll_action(pygame, current):
    quit_req = False
    for ev in pygame.event.get():
        if ev.type == pygame.QUIT:
            quit_req = True
        elif ev.type == pygame.KEYDOWN and ev.key == pygame.K_ESCAPE:
            quit_req = True
    keys = pygame.key.get_pressed()
    if keys[pygame.K_LEFT] or keys[pygame.K_a]:
        return LEFT, quit_req
    if keys[pygame.K_RIGHT] or keys[pygame.K_d]:
        return RIGHT, quit_req
    return NONE, quit_req


def main(args):
    import pygame
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    cfg, vae, diff = load_models(args, device)
    z_history, actions = initial_context(vae, cfg, args.seed, device)
    sigmas = make_schedule(cfg, args.steps, args.sigma_max, str(device))

    pygame.init()
    screen = pygame.display.set_mode((W * args.scale, H * args.scale))
    pygame.display.set_caption("nanoOasis Breakout (DiT model)")
    clock = pygame.time.Clock()
    running = True
    while running:
        action, quit_req = poll_action(pygame, actions[-1])
        if quit_req:
            break
        z_ctx = z_history[:, 1:]
        full_actions = torch.tensor(actions[1:] + [action], dtype=torch.long, device=device)
        new_lat = sample_next_frame(diff, z_ctx, full_actions, sigmas, args.sigma_stab, args.sampler)
        z_history = torch.cat([z_ctx, new_lat], dim=1)
        actions = actions[1:] + [action]
        frame = decode_latent(vae, new_lat)
        surf = pygame.surfarray.make_surface(np.transpose(frame, (1, 0, 2)))
        screen.blit(pygame.transform.scale(surf, (W * args.scale, H * args.scale)), (0, 0))
        pygame.display.flip()
        clock.tick(args.fps)
    pygame.quit()


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--config", default="breakout_100k_latents")
    p.add_argument("--vae", default="checkpoints/vae_breakout_100k.pt")
    p.add_argument("--ckpt", default="checkpoints/dit_breakout_100k_latents.pt")
    p.add_argument("--steps", type=int, default=4, help="EDM steps per predicted frame")
    p.add_argument("--sampler", choices=["euler", "heun"], default="euler")
    p.add_argument("--sigma-stab", type=float, default=0.1)
    p.add_argument("--sigma-max", type=float, default=0.0)
    p.add_argument("--fps", type=int, default=4)
    p.add_argument("--scale", type=int, default=4)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--raw", action="store_true", help="use raw model weights instead of EMA")
    main(p.parse_args())
